"""Synthetic streaming byte proofs and resource bounds; no network/model data."""

import pytest

from profile_streaming import DiskMeter, build, generate, prove_reference


def test_small_retained_and_streaming_three_way_proofs_agree(tmp_path):
    import shutil

    source = tmp_path / "source"
    generate(source, tensors=7, elements=2048, shard_tensors=2)
    retained = build(source, tmp_path / "retained", "retained", tmp_path)
    shutil.rmtree(tmp_path / "retained")
    streamed = build(source, tmp_path / "streaming", "streaming", tmp_path)
    assert (
        retained["canonical_tensor_hash_catalog_sha256"]
        == streamed["canonical_tensor_hash_catalog_sha256"]
    )
    assert (
        retained["per_tensor_changed_elements"]
        == streamed["per_tensor_changed_elements"]
    )
    assert streamed["actual_changed_elements"] == (7 * 2048) // 100
    assert streamed["independent_literal_oracle_bytes_equal"]
    assert streamed["three_way_hash_catalogs_equal"]
    assert streamed["peak_logical_disk_bytes"] < retained["peak_logical_disk_bytes"]
    assert not streamed["full_8b_projection_measured"]


def test_oversized_synthetic_input_rejected_before_files(tmp_path):
    with pytest.raises(ValueError, match="256MiB"):
        generate(tmp_path / "source", tensors=400, elements=1048576)
    assert not (tmp_path / "source").exists()


def test_disk_meter_tracks_real_allocated_blocks_and_rejects_cap(tmp_path, monkeypatch):
    import profile_streaming as module

    (tmp_path / "data").write_bytes(b"x" * 4096)
    meter = DiskMeter(tmp_path)
    meter.sample()
    assert meter.logical == 4096
    assert meter.allocated >= 4096
    monkeypatch.setattr(module, "MAX_DISK_BYTES", 1024)
    with pytest.raises(RuntimeError, match="256MiB"):
        meter.sample()


def test_corrupt_reference_cannot_pass_independent_proof(tmp_path):
    from chalkcompute._weights_format import WeightManifest

    source = tmp_path / "source"
    generate(source, tensors=3, elements=1024)
    out = tmp_path / "stream"
    build(source, out, "streaming", tmp_path)
    root = out / "reference"
    manifest = WeightManifest.from_json((root / "manifest.json").read_bytes())
    target = root / manifest.tensors[0].file
    with target.open("r+b") as writer:
        writer.seek(-1, 2)
        writer.write(b"!")
    with pytest.raises(RuntimeError, match="checksum"):
        prove_reference(root, {}, manifest)


def test_runner_rejects_unbounded_deadline_before_work(tmp_path):
    from profile_streaming_benchmark import run

    with pytest.raises(ValueError, match="120seconds"):
        run(tmp_path / "out", tmp_path, timeout=121)
    assert not (tmp_path / "out").exists()


def test_trainer_and_patch_agreement_cannot_bypass_literal_oracle(
    tmp_path, monkeypatch
):
    import profile_streaming as module
    import torch

    def wrong_mantissa_mutation(base, count):
        result = base.clone()
        bits = result.view(torch.int16).reshape(-1)
        indices = torch.arange(count) * base.numel() // count
        bits[indices] = bits[indices].bitwise_xor(2)
        return result

    source = tmp_path / "source"
    generate(source, tensors=3, elements=1024)
    monkeypatch.setattr(module, "mutate", wrong_mantissa_mutation)
    with pytest.raises(RuntimeError, match="independently regenerated bytes"):
        build(source, tmp_path / "out", "streaming", tmp_path)


def test_timeout_removes_owned_inputs_and_records_cleanup(tmp_path, monkeypatch):
    import json
    import subprocess

    import profile_streaming_benchmark as module

    owned = []

    def timed_out(command, **kwargs):
        from pathlib import Path

        source = Path(command[command.index("--source") + 1])
        source.mkdir()
        (source / "partial-data").write_bytes(b"partial")
        owned.append(source.parent)
        raise subprocess.TimeoutExpired(command, kwargs["timeout"])

    monkeypatch.setattr(module.subprocess, "run", timed_out)
    out = tmp_path / "out"
    with pytest.raises(subprocess.TimeoutExpired):
        module.run(out, tmp_path)
    assert len(owned) == 1 and not owned[0].exists()
    assert json.loads((out / "local-cleanup.json").read_text())["owned_tempdir_removed"]
    assert not (out / "result.json").exists()
